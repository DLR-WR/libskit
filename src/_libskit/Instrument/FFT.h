/**
 * @file FFT.h
 * @brief Fast Fourier Transform utilities for spectral processing.
 *
 * This header provides efficient FFT and inverse FFT implementations used
 * throughout the libskit library for instrumental broadening via convolution in frequency domain
 */
#ifndef FFT_H
#define FFT_H

#include <Eigen/Core>

/**
 * @brief Perform in-place Fast Fourier Transform.
 *
 * Computes the discrete Fourier transform of the input complex vector using
 * an efficient FFT algorithm. The transform is performed in-place, modifying
 * the input vector directly.
 *
 * The FFT converts from time/space domain to frequency domain. NOTE: this
 * implementation uses the **non-standard +2πi sign convention** for the
 * forward transform (and -2πi for the inverse), so:
 *     X[k] = Σ(n=0 to N-1) x[n] * exp(+2πi * k * n / N)
 * Most textbooks use exp(-2πi * k * n / N); callers that combine libskit's
 * fft() with externally-computed kernels must account for this.
 *
 * @tparam T The underlying floating-point type (e.g., float, double).
 * @param a Complex vector to be transformed (modified in-place).
 *          Size must be a power of 2.
 *
 * @see ifft() for the inverse transform
 */
void fft(Eigen::VectorXcd &a);

/**
 * @brief Perform in-place Inverse Fast Fourier Transform.
 *
 * Computes the inverse discrete Fourier transform of the input complex vector
 * using an efficient IFFT algorithm. The transform is performed in-place,
 * modifying the input vector directly.
 *
 * The IFFT converts from frequency domain back to time/space domain.
 * Pairs with the forward fft() above (note its non-standard +2πi sign):
 *     x[n] = (1/N) * Σ(k=0 to N-1) X[k] * exp(-2πi * k * n / N)
 *
 * @tparam T The underlying floating-point type (e.g., float, double).
 * @param a Complex vector in frequency domain to be inverse transformed
 *          (modified in-place). Size must match the original input to fft().
 *
 * @note This function assumes the input was generated by fft() and applies
 *       the appropriate normalization factor (1/N).
 *
 * @see fft() for the forward transform
 */
void ifft(Eigen::VectorXcd &a);

#endif // FFT_H

# ---------------------------------------------------------------------------
# Auto-load bundled databases
# ---------------------------------------------------------------------------
# When installed via pip the CSV files live in <package>/data/. Activating
# the bundled Database here lets users skip any manual setup; passing
# ``db=`` to a model constructor remains optional and falls through to
# whichever Database is active at construction time.
try:
    _bundled = Database.bundled()
    # Skip activation entirely when the CSVs are not present so the C++
    # loader does not spam stderr in source-tree CI runs.
    from .database import _REQUIRED_DB_FILES as _REQ
    if all((_bundled.path / f).is_file() for f in _REQ):
        _bundled.activate(verbose=0)
except Exception:
    # Bundled data missing or corrupt — user can still construct
    # ``Database.from_path(...)`` manually and pass it via ``db=``.
    pass


# ---------------------------------------------------------------------------
# Database-aware Python wrappers around pybind plasma models
# ---------------------------------------------------------------------------
# Each wrapper accepts an optional ``db=Database`` keyword argument. When
# provided it is forwarded to ``db.activate()`` before construction so the
# C++ globals match the requested database; when omitted the currently-
# active Database is used (the bundled one is auto-activated above).

def _activate(db: "Database | None") -> None:
    if db is not None:
        db.activate()


class LTEModel(_LTEModel_cpp):
    """LTE plasma model, optionally bound to a specific :class:`Database`.

    See the C++ base class for the full positional argument list. The
    keyword-only ``db`` argument selects which atomic database backs
    this model; when omitted the currently-active database is used
    (the bundled CSVs are auto-activated on ``import libskit``).
    """

    def __init__(self, *args, db: "Database | None" = None, **kwargs):
        _activate(db)
        super().__init__(*args, **kwargs)


class LTELayers(_LTELayers_cpp):
    """Stack of LTE layers; see :class:`LTEModel` for ``db`` usage."""

